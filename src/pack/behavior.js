// LC928 writeback, EC73 post-step. Byte map (all actors):
//   b0 actor id (0 empty, 1 dormant-spawn) | b1 anim/phase | b2 X-lo
//   b3 X-hi | b4 Y-lo | b5 Y-hi | b6 dir/state | b7 aux | b8 timer-a
//   b9 countdown (dec/f, saturates 0) | b10 behavior state | b11 timer-b
//   b12 aux | b13 HP (== stat-table byte0 for typed actors).
// b1/b6/b7/b8/b10/b11/b12 roles are per-actor (documented below); b9/b13
// are generic. Player slot0 reuses the file (b9 = invuln timer, b11 =
// death/respawn counter, b13 = visual-HP 0xFF scale) -- out of scope.
//
// Dispatch (C9A4): X = $40 dungeon ($14 bit3 set) / $60 overhead ->
// EA3A pages the bank (LE61B MMC1 serial) and sets ($7A) = vector base:
//   dungeon ($7A) = $8002 (bank6 rel 2), entry = word[actor id];
//   tank    ($7A) = $8006 (bank4 rel 6), entry = word[type-1].
