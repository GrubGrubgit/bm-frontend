export function spriteBanksFor(level) {
  if (level >= 1 && level <= 8) return [SPR_BANK_DUNGEON[level]];
  if (level >= 9 && level <= 16) return [SPR_BANK_OVERHEAD, BG_CHR_BANK[level]];
  return [];
}
export function isPureSpriteBank(level, bank4k) {
  if (level >= 1 && level <= 8) return bank4k === SPR_BANK_DUNGEON[level];
  if (level >= 9 && level <= 16) return bank4k === SPR_BANK_OVERHEAD;
  return false;
}
