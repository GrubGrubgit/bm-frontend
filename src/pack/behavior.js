//   (5f-sampled), b1 3-phase anim, b6 $f1 left / $0f right flips at turns,
//   b10 1 (enter/fall) -> 0 (patrol), b11 follows (8i mod 13) early then
//   diverges (open), b13 HP = $04.
// - $59 dungeon converter output: dormant 01 -> $59 on camera approach
//   (B0: slot11 @f955, slot10 @f980, HP $08); slot11 $59->$02 @f1080
//   (form change vs death -- open).
// - $45 tank flyer: slow +X drift, rises -8/f to yhi $16 then hovers a
//   3-cycle bob (7c/86/81), b6 = $07 const, b8 countdown to $4f floor
//   (trigger TBD), b13 HP = $20 (= e14 byte0).
// - $23 powerup: static, b11 loiter countdown (~-1/4f), b8 = $d8 const.
// - $5B boss egg: b11 $C0-set, -1/f to 0 (~192f), morphs to $63 with
//   exact A571 init (b6=0,b7=$08,b10=0,b11=0,b13=$80=128); $63 boss
//   dormant ~280f post-morph, then activates (b11 counts up).
