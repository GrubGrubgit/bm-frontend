// src/pack/sprites.js -- 6.4d sprite CHR banks + 6.4a sprite palettes. Pure, no DOM.
// Engine (fixed bank7): area init C6EF sets D4=LC72A[$14] -> MMC1 CHR0
// (applied EC34/LE664); D5=LC71A[$14] -> CHR1 (matches BG_CHR_BANK).
// r2000 $90 = dungeons (8x8 sprites, bank chr0); $B0 = overhead (8x16:
// even tiles chr0, odd tiles chr1). Sprite sub-palettes 0-2 global from
// LC6BF/LC6CB (identical 12B, selected by $FF&$20 = 8x16 mode); sub-3
// bytes 1-3 rewritten every frame by C642 from LC651[$10&7] (period 8f).
// All proven headless 2026-11-25 (tools/verify-pack-6.4ad.mjs).
