// Dungeon base proven by word[85] = $a40b (actor-$55 init, cf 6.1 note);
// tank base proven by word[97] = $a571 (type-$62 hatch init, cf item 4).
// Holes: dungeon words 55/87 are null (unused ids). Table ends: dungeon
// 146 words (idx146 = 0x5b4c out of range), tank 140-word read (valid run
// ends ~idx137 0xa50c, tail TBD -- pinned exact, see suite).
//
